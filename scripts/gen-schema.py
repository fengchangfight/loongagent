#!/usr/bin/env python3
"""Generate Rust and TypeScript types from crates/schema/protocol.toml.

Single source of truth (ADR-0002 schema-first, ADR-0013 two languages).
Outputs, all generated — never edit them by hand:

    crates/schema/src/generated.rs               Rust types + name tables
    crates/schema/tests/generated_roundtrip.rs   conformance test over samples
    clients/ts/protocol.generated.ts             TypeScript types for the web client
    clients/ts/protocol.samples.json             example payloads (also docs)

Usage:
    scripts/gen-schema.py           write the files
    scripts/gen-schema.py --check   fail if the files on disk are stale (CI)
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
IDL = ROOT / "crates" / "schema" / "protocol.toml"
RUST_OUT = ROOT / "crates" / "schema" / "src" / "generated.rs"
TEST_OUT = ROOT / "crates" / "schema" / "tests" / "generated_roundtrip.rs"
TS_OUT = ROOT / "clients" / "ts" / "protocol.generated.ts"
SAMPLES_OUT = ROOT / "clients" / "ts" / "protocol.samples.json"

BANNER = "// @generated by scripts/gen-schema.py from crates/schema/protocol.toml — DO NOT EDIT"

PRIMITIVES = {
    "string": ("String", "string"),
    "bool": ("bool", "boolean"),
    "i64": ("i64", "number"),
    "u64": ("u64", "number"),
    "json": ("serde_json::Value", "Json"),
}


def fail(msg: str) -> None:
    print(f"gen-schema: error: {msg}", file=sys.stderr)
    sys.exit(1)


def snake(name: str) -> str:
    out = []
    for i, ch in enumerate(name):
        if ch.isupper() and i:
            out.append("_")
        out.append(ch.lower())
    return "".join(out)


def camel(name: str) -> str:
    parts = name.replace("-", "_").replace(".", "_").split("_")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


class Schema:
    def __init__(self, doc: dict):
        self.version: str = doc["schema_version"]
        self.types: dict[str, dict] = {}
        for t in doc.get("types", []):
            if t["name"] in self.types:
                fail(f"duplicate type {t['name']}")
            self.types[t["name"]] = t
        self.methods: list[dict] = doc.get("methods", [])
        self.events: list[dict] = doc.get("events", [])
        self.notifications: list[dict] = doc.get("notifications", [])
        self._validate()

    # ---------------------------------------------------------------- checks
    def resolve(self, name: str) -> dict:
        if name in PRIMITIVES:
            return {"kind": "primitive", "name": name}
        if name in self.types:
            return self.types[name]
        fail(f"type {name!r} is not declared")

    def _validate(self) -> None:
        for t in self.types.values():
            kind = t["kind"]
            if kind == "alias":
                if t["rust"] is None or t["ts"] is None:
                    fail(f"alias {t['name']} needs rust and ts")
            elif kind == "enum":
                if not t.get("variants"):
                    fail(f"enum {t['name']} has no variants")
                wires = [v["wire"] for v in t["variants"]]
                if len(wires) != len(set(wires)):
                    fail(f"enum {t['name']} has duplicate wire values")
            elif kind == "struct":
                seen = set()
                for f in t.get("fields", []):
                    if f["name"] in seen:
                        fail(f"struct {t['name']} has duplicate field {f['name']}")
                    seen.add(f["name"])
                    self.resolve(f["type"])
                    if f.get("optional") and f["type"] == "json":
                        fail(f"{t['name']}.{f['name']}: optional json is ambiguous; use a struct")
            else:
                fail(f"unknown kind {kind!r} for {t['name']}")
        for m in self.methods:
            for key in ("params", "result"):
                if m.get(key):
                    if self.resolve(m[key])["kind"] != "struct":
                        fail(f"method {m['name']}: {key}={m[key]} must be a struct")
        for e in self.events:
            payload = self.resolve(e["payload"])
            if payload["kind"] != "struct":
                fail(f"event {e['name']}: payload must be a struct")
        for n in self.notifications:
            if self.resolve(n["payload"])["kind"] != "struct":
                fail(f"notification {n['name']}: payload must be a struct")
            if not n.get("transient"):
                fail(
                    f"notification {n['name']}: a notification must declare `transient = true` — "
                    "anything durable belongs in the event set, which is the log"
                )
        for name in (
            [m["name"] for m in self.methods]
            + [e["name"] for e in self.events]
            + [n["name"] for n in self.notifications]
        ):
            if not name or " " in name:
                fail(f"bad wire name {name!r}")

    # ------------------------------------------------------- sample payloads
    def sample(self, type_name: str) -> object:
        t = self.resolve(type_name)
        if t["kind"] == "primitive":
            return {"string": "<string>", "bool": True, "i64": 1, "u64": 1, "json": {}}[t["name"]]
        if t["kind"] == "alias":
            return self.sample_alias(t)
        if t["kind"] == "enum":
            return t["variants"][0]["wire"]
        return {f["name"]: self.sample_field(f) for f in t.get("fields", [])}

    def sample_alias(self, t: dict) -> object:
        return {
            "u64": 1, "i64": 1, "string": "<string>", "bool": True,
            "serde_json::Value": {}, "JsonValue": {}, "number": 1,
        }.get(t["rust"], {})

    def sample_field(self, f: dict) -> object:
        value = self.sample(f["type"])
        return [value] if f.get("list") else value

    # ------------------------------------------------------------ Rust code
    def rust(self) -> str:
        out = [BANNER, "", "use serde::{Deserialize, Serialize};", ""]
        out.append(f'/// Protocol schema version (ADR-0002).')
        out.append(f'pub const SCHEMA_VERSION: &str = "{self.version}";')
        out.append("")
        for t in self.types.values():
            if t["kind"] == "alias":
                if t.get("doc"):
                    out.append(f"/// {t['doc']}")
                out.append(f"pub type {t['name']} = {t['rust']};")
                out.append("")
        for t in self.types.values():
            if t["kind"] != "enum":
                continue
            if t.get("doc"):
                out.append(f"/// {t['doc']}")
            out.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]")
            out.append(f"pub enum {t['name']} {{")
            for v in t["variants"]:
                if v.get("doc"):
                    out.append(f"    /// {v['doc']}")
                out.append(f'    #[serde(rename = "{v["wire"]}")]')
                out.append(f"    {v['name']},")
            out.append("}")
            out.append("")
        for t in self.types.values():
            if t["kind"] != "struct":
                continue
            if t.get("doc"):
                out.append(f"/// {t['doc']}")
            out.append("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]")
            out.append(f"pub struct {t['name']} {{")
            for f in t.get("fields", []):
                if f.get("doc"):
                    out.append(f"    /// {f['doc']}")
                out.append(f"    pub {f['name']}: {self.rust_field(f)},")
            out.append("}")
            out.append("")
        out.append("/// JSON-RPC method names (ADR-0002).")
        out.append("pub mod method {")
        for m in self.methods:
            if m.get("doc"):
                out.append(f"    /// {m['doc']}")
            out.append(f'    pub const {m["name"].replace(".", "_").upper()}: &str = "{m["name"]}";')
        out.append("}")
        out.append("")
        out.append("/// Event kind names (ADR-0003).")
        out.append("pub mod event {")
        for e in self.events:
            out.append(f'    pub const {e["name"].replace(".", "_").upper()}: &str = "{e["name"]}";')
        out.append("}")
        out.append("")
        out.append("/// Transient notifications: server to client, **never logged**.")
        out.append("///")
        out.append("/// These are a preview channel, not a record: a reader that misses one has")
        out.append("/// lost nothing, because the event that follows carries the same content in")
        out.append("/// its final form. Keeping them out of the event set is what lets the log")
        out.append("/// stay the truth without a stream of partial states in it.")
        out.append("pub mod notification {")
        for n in self.notifications:
            out.append(f'    pub const {n["name"].replace(".", "_").upper()}: &str = "{n["name"]}";')
        out.append("}")
        out.append("")
        out.append("/// Event kinds. The bool is the `ignorable` envelope marker (ADR-0003).")
        out.append("pub const EVENT_KINDS: &[(&str, bool)] = &[")
        for e in self.events:
            out.append(f'    ("{e["name"]}", {str(bool(e.get("ignorable", True))).lower()}),')
        out.append("];")
        out.append("")
        out.append("/// `Some(ignorable)` for a known event kind, `None` for an unknown one.")
        out.append("/// Readers MUST skip unknown kinds when ignorable, and fail loudly")
        out.append("/// otherwise — never render a session they do not understand.")
        out.append("pub fn is_ignorable_event(kind: &str) -> Option<bool> {")
        out.append("    EVENT_KINDS.iter().find(|(k, _)| *k == kind).map(|(_, i)| *i)")
        out.append("}")
        out.append("")
        return "\n".join(out)

    def rust_field(self, f: dict) -> str:
        t = self.resolve(f["type"])
        if t["kind"] == "primitive":
            base = PRIMITIVES[t["name"]][0]
        elif t["kind"] == "alias":
            base = t["name"]
        else:
            base = t["name"]
        if f.get("list"):
            base = f"Vec<{base}>"
        if f.get("optional"):
            base = f"Option<{base}>"
        return base

    # -------------------------------------------------------------- TS code
    def ts(self) -> str:
        out = [BANNER, ""]
        out.append("export type JsonValue =")
        out.append("  | null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };")
        out.append("")
        out.append(f'export const SCHEMA_VERSION = "{self.version}";')
        out.append("")
        for t in self.types.values():
            if t["kind"] == "alias":
                if t.get("doc"):
                    out.append(f"/** {t['doc']} */")
                out.append(f"export type {t['name']} = {t['ts']};")
                out.append("")
        for t in self.types.values():
            if t["kind"] != "enum":
                continue
            if t.get("doc"):
                out.append(f"/** {t['doc']} */")
            union = " | ".join(f'"{v["wire"]}"' for v in t["variants"])
            out.append(f"export type {t['name']} = {union};")
            out.append("")
        for t in self.types.values():
            if t["kind"] != "struct":
                continue
            if t.get("doc"):
                out.append(f"/** {t['doc']} */")
            out.append(f"export interface {t['name']} {{")
            for f in t.get("fields", []):
                if f.get("doc"):
                    out.append(f"  /** {f['doc']} */")
                opt = "?" if f.get("optional") else ""
                out.append(f"  {f['name']}{opt}: {self.ts_type(f['type'], f.get('list'))};")
            out.append("}")
            out.append("")
        out.append("export const METHODS = {")
        for m in self.methods:
            out.append(f'  {camel(m["name"])}: "{m["name"]}",')
        out.append("} as const;")
        out.append("")
        out.append("export const EVENTS = {")
        for e in self.events:
            out.append(f'  {camel(e["name"])}: "{e["name"]}",')
        out.append("} as const;")
        out.append("")
        out.append("export const NOTIFICATIONS = {")
        for n in self.notifications:
            out.append(f'  {camel(n["name"])}: "{n["name"]}",')
        out.append("} as const;")
        out.append("")
        out.append("export type MethodName = (typeof METHODS)[keyof typeof METHODS];")
        out.append("export type EventKind = (typeof EVENTS)[keyof typeof EVENTS];")
        out.append("")
        out.append("/** Event kinds a reader may skip when it does not understand them. */")
        ignorable = [e["name"] for e in self.events if e.get("ignorable", True)]
        out.append(f"export const IGNORABLE_EVENTS: readonly EventKind[] = {json.dumps(ignorable, indent=2)} as const;")
        out.append("")
        return "\n".join(out)

    def ts_type(self, name: str, is_list: bool | None) -> str:
        t = self.resolve(name)
        if t["kind"] == "primitive":
            base = PRIMITIVES[t["name"]][1]
        else:
            base = t["name"]
        return f"{base}[]" if is_list else base

    # ------------------------------------------------------------ test code
    def test(self) -> str:
        out = [BANNER, ""]
        out.append("use loong_schema::generated as g;")
        out.append("use serde_json::Value;")
        out.append("")
        out.append("fn roundtrip<T>(json: &str)")
        out.append("where")
        out.append("    T: serde::de::DeserializeOwned + serde::Serialize,")
        out.append("{")
        out.append("    let value: Value = serde_json::from_str(json).expect(\"sample parses\");")
        out.append("    let typed: T = serde_json::from_value(value.clone()).expect(\"sample deserializes\");")
        out.append("    assert_eq!(serde_json::to_value(&typed).unwrap(), value, \"round-trip is lossless\");")
        out.append("}")
        out.append("")
        for t in self.types.values():
            if t["kind"] != "struct":
                continue
            sample = json.dumps(self.sample(t["name"]), indent=None, separators=(",", ": "))
            out.append("#[test]")
            out.append(f"fn roundtrip_{snake(t['name'])}() {{")
            out.append(f'    roundtrip::<g::{t["name"]}>(r#"{sample}"#);')
            out.append("}")
            out.append("")
        out.append("#[test]")
        out.append("fn declared_events_match_the_envelope_table() {")
        for e in self.events:
            ign = str(bool(e.get("ignorable", True))).lower()
            out.append(
                f'    assert_eq!(g::is_ignorable_event("{e["name"]}"), Some({ign}));'
            )
        out.append('    assert_eq!(g::is_ignorable_event("not.a.real.event"), None);')
        out.append("}")
        out.append("")
        out.append("#[test]")
        out.append("fn every_event_payload_roundtrips() {")
        for e in self.events:
            sample = json.dumps(self.sample(e["payload"]), separators=(",", ": "))
            out.append(f'    roundtrip::<g::{e["payload"]}>(r#"{sample}"#);')
        out.append("}")
        out.append("")
        return "\n".join(out)

    # --------------------------------------------------------------- samples
    def samples(self) -> str:
        return json.dumps(
            {
                "schema_version": self.version,
                "types": {t["name"]: self.sample(t["name"]) for t in self.types.values() if t["kind"] == "struct"},
                "methods": [{"name": m["name"], "params": m.get("params"), "result": m.get("result")} for m in self.methods],
                "events": [{"name": e["name"], "payload": e["payload"], "ignorable": e.get("ignorable", True)} for e in self.events],
                "notifications": [
                    {"name": n["name"], "payload": n["payload"]} for n in self.notifications
                ],
            },
            indent=2,
            sort_keys=False,
        ) + "\n"


def rustfmt(text: str) -> str:
    """Generated Rust is written formatted, so `cargo fmt --check` and this
    generator cannot disagree about the same file.

    rustfmt is required (not optional): silently skipping it would make the check
    pass on a machine that cannot produce the same bytes, which is the opposite of
    what a check is for.
    """
    exe = shutil.which("rustfmt")
    if not exe:
        print(
            "gen-schema: rustfmt is not installed; generated Rust would not be checked\n"
            "  run: rustup component add rustfmt",
            file=sys.stderr,
        )
        raise SystemExit(2)
    with tempfile.NamedTemporaryFile("w", suffix=".rs", delete=False) as handle:
        handle.write(text)
        path = handle.name
    try:
        # In place, not `--emit stdout`: that mode prefixes the output with the input
        # file name, which a random temp path would bake into a generated file.
        subprocess.run(
            [exe, "--edition", "2021", path],
            check=True,
            capture_output=True,
            text=True,
        )
        return Path(path).read_text()
    except subprocess.CalledProcessError as error:
        print(f"gen-schema: rustfmt failed: {error.stderr}", file=sys.stderr)
        raise SystemExit(2) from error
    finally:
        Path(path).unlink(missing_ok=True)


def main() -> int:
    check = "--check" in sys.argv[1:]
    schema = Schema(tomllib.loads(IDL.read_text()))
    outputs = {
        RUST_OUT: rustfmt(schema.rust()),
        TEST_OUT: rustfmt(schema.test()),
        TS_OUT: schema.ts(),
        SAMPLES_OUT: schema.samples(),
    }
    stale = []
    for path, content in outputs.items():
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(path.relative_to(ROOT))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path.relative_to(ROOT)}")
    if check:
        if stale:
            print("gen-schema: generated files are stale:", file=sys.stderr)
            for p in stale:
                print(f"  - {p}", file=sys.stderr)
            print("  run scripts/gen-schema.py", file=sys.stderr)
            return 1
        print("gen-schema --check: generated files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
