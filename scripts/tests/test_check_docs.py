#!/usr/bin/env python3
"""Tests for scripts/check-docs.py, the document contract gate.

Run from the repository root:

    python3 -m unittest scripts.tests.test_check_docs -v

Each test builds a small tree in a temporary directory and runs the real command
as a subprocess, because the interface that matters is the command-line one:
the seeded defect, the `FAIL path:line` line, the exit code and the baseline
ratchet. A test that imported internals could pass while the gate itself was
broken.

Some tests need the whole default check set, not just one new check: the
baseline has to make a bare `check-docs.py` run green. Those build a fixture
repository whose crate map is generated by the real `scripts/layering_rules.py`
copied into the tree, so the `crate-map` check sees the same generator it sees
in the repository.
"""
from __future__ import annotations

import importlib.util
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

SCRIPTS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCRIPT = os.path.join(SCRIPTS, "check-docs.py")
LAYERING = os.path.join(SCRIPTS, "layering_rules.py")

BASELINE = "scripts/doc-contract-baseline.txt"

# A complete header for a normal maintained document. The defaults are the
# values a fixture passes when nothing about the header is under test.
def header(
    up: str | None = "[04 System overview](../04-system-overview.md)",
    authority: str | None = "[ADR-0001](../decisions/0001-fixture.md)",
    code: str | None = "`crates/schema/src/lib.rs`",
    verify: str | None = "`cargo test -p loong-schema`",
) -> str:
    lines = []
    if up is not None:
        lines.append(f"- **Up:** {up}")
    if authority is not None:
        lines.append(f"- **Authority:** {authority}")
    if code is not None:
        lines.append(f"- **Code:** {code}")
    if verify is not None:
        lines.append(f"- **Verify:** {verify}")
    return "\n".join(lines) + "\n"


def document(title: str, body: str = "") -> str:
    return f"# {title}\n\n{body}"


def sized(title: str, lines: int) -> str:
    """A document whose file is exactly `lines` lines long."""
    body = "".join(f"line {number}\n" for number in range(2, lines + 1))
    return f"# {title}\n{body}"


def load_layering():
    """Load the real layering rules, so the fixture's crate set cannot drift."""
    spec = importlib.util.spec_from_file_location("layering_rules", LAYERING)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class GateTest(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = self._tmp.name

    def path(self, relative: str) -> str:
        return os.path.join(self.root, *relative.split("/"))

    def write(self, relative: str, content: str) -> str:
        path = self.path(relative)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(content)
        return path

    def init_git(self) -> None:
        subprocess.run(["git", "init", "-q"], cwd=self.root, check=True)
        subprocess.run(["git", "add", "-A"], cwd=self.root, check=True)

    def run_gate(self, *args: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, SCRIPT, "--root", self.root, *args],
            capture_output=True,
            text=True,
            cwd=self.root,
        )

    def assert_passes(self, result: subprocess.CompletedProcess[str]) -> None:
        output = result.stdout + result.stderr
        self.assertEqual(result.returncode, 0, f"expected exit 0\noutput:\n{output}")

    def assert_fails(self, result: subprocess.CompletedProcess[str], *needles: str) -> None:
        output = result.stdout + result.stderr
        self.assertEqual(result.returncode, 1, f"expected exit 1\noutput:\n{output}")
        for needle in needles:
            self.assertIn(needle, output)

    # -- a complete fixture repository ---------------------------------------

    def write_full_tree(self, broken_design: bool = False) -> None:
        """A small repository every default check can pass without a baseline."""
        layering = load_layering()
        os.makedirs(self.path("scripts"), exist_ok=True)
        shutil.copyfile(LAYERING, self.path("scripts/layering_rules.py"))
        for name in sorted(layering.ALLOWED):
            directory = layering.crate_directory(name)
            source = "main.rs" if name in layering.DIRECTORY_EXCEPTIONS else "lib.rs"
            self.write(f"crates/{directory}/src/{source}", "//! Fixture crate.\n")

        generated = subprocess.run(
            [sys.executable, self.path("scripts/layering_rules.py"), "--emit-map", self.root],
            capture_output=True,
            text=True,
            check=True,
        )
        self.write("docs/crate-map.md", generated.stdout)

        self.write("README.md", document("Fixture", "A fixture repository.\n"))
        self.write(
            "docs/README.md",
            document(
                "Docs",
                "\n".join(
                    [
                        "- **Up:** [04 System overview](04-system-overview.md)",
                        "- **Code:** `docs/README.md`",
                        "- **Verify:** `python3 scripts/check-docs.py`",
                        "",
                        "| Doc | Topic |",
                        "|---|---|",
                        "| [02-topics.md](02-topics.md) | topics |",
                        "| [03-architecture.md](03-architecture.md) | architecture |",
                        "| [04-system-overview.md](04-system-overview.md) | overview |",
                        "| [crate-map.md](crate-map.md) | generated |",
                        "| [decisions/](decisions/) | ADRs |",
                        "| [design/](design/) | design |",
                        "",
                    ]
                ),
            ),
        )
        self.write(
            "docs/02-topics.md",
            document(
                "Topics",
                header(
                    up="[04 System overview](04-system-overview.md)",
                    authority="[ADR-0001](decisions/0001-fixture.md)",
                )
                + "\n## T-01 · fixture\n\nA fixture topic.\n",
            ),
        )
        self.write(
            "docs/03-architecture.md",
            document(
                "Architecture",
                header(
                    up="[04 System overview](04-system-overview.md)",
                    authority="[ADR-0001](decisions/0001-fixture.md)",
                ),
            ),
        )
        self.write(
            "docs/04-system-overview.md",
            document(
                "Overview",
                header(
                    up="[03](03-architecture.md)",
                    authority="[ADR-0001](decisions/0001-fixture.md)",
                ),
            ),
        )
        self.write("docs/design/README.md", document("Design", header()))
        self.write(
            "docs/decisions/0001-fixture.md",
            document(
                "ADR-0001",
                "- **Up:** [04 System overview](../04-system-overview.md)\n\n"
                "- **Status:** Accepted\n\nA fixture decision.\n",
            ),
        )
        if broken_design:
            self.write("docs/design/broken.md", document("Broken", "No header yet.\n"))

    # -- headers -------------------------------------------------------------

    def test_complete_header_passes(self) -> None:
        self.write("docs/design/fixture.md", document("Fixture", header()))
        self.init_git()
        self.assert_passes(self.run_gate("--check", "headers"))

    def test_missing_up_fails(self) -> None:
        self.write("docs/design/fixture.md", document("Fixture", header(up=None)))
        self.init_git()
        self.assert_fails(
            self.run_gate("--check", "headers"),
            "FAIL docs/design/fixture.md",
            "Up",
        )

    def test_adr_needs_only_up(self) -> None:
        self.write(
            "docs/decisions/0001-fixture.md",
            document("ADR-0001", "- **Up:** [04](../04-system-overview.md)\n"),
        )
        self.init_git()
        self.assert_passes(self.run_gate("--check", "headers"))

    def test_index_root_needs_code_and_verify(self) -> None:
        self.write(
            "docs/README.md",
            document(
                "Docs",
                "- **Code:** `docs/README.md`\n- **Verify:** `python3 scripts/check-docs.py`\n",
            ),
        )
        self.init_git()
        self.assert_passes(self.run_gate("--check", "headers"))

        self.write(
            "docs/README.md",
            document("Docs", "- **Code:** `docs/README.md`\n"),
        )
        self.assert_fails(self.run_gate("--check", "headers"), "Verify")

    def test_readme_with_a_header_needs_no_up(self) -> None:
        self.write(
            "README.md",
            document(
                "Fixture",
                "- **Authority:** [ADR-0001](docs/decisions/0001-fixture.md)\n"
                "- **Code:** `README.md`\n"
                "- **Verify:** `python3 scripts/check-docs.py`\n",
            ),
        )
        self.init_git()
        self.assert_passes(self.run_gate("--check", "headers"))

    def test_verify_prose_without_a_command_fails(self) -> None:
        self.write(
            "docs/design/fixture.md",
            document("Fixture", header(verify="not tested")),
        )
        self.init_git()
        self.assert_fails(self.run_gate("--check", "headers"), "Verify", "command")

    # -- lengths -------------------------------------------------------------

    def test_design_document_over_budget_fails(self) -> None:
        self.write("docs/design/big.md", sized("Big", 260))
        self.init_git()
        self.assert_fails(self.run_gate("--check", "lengths"), "260 > 250")

    def test_docs_04_at_its_budget_passes(self) -> None:
        self.write("docs/04-system-overview.md", sized("Overview", 180))
        self.init_git()
        self.assert_passes(self.run_gate("--check", "lengths"))

    # -- code paths ----------------------------------------------------------

    def test_missing_code_path_fails(self) -> None:
        self.write(
            "docs/design/fixture.md",
            document("Fixture", header(code="`crates/schema/src/missing.rs`")),
        )
        self.init_git()
        self.assert_fails(
            self.run_gate("--check", "code-paths"),
            "crates/schema/src/missing.rs",
            "does not exist",
        )

    # -- reachability --------------------------------------------------------

    def test_design_document_reaches_both_roots(self) -> None:
        self.write("docs/04-system-overview.md", document("Overview"))
        self.write(
            "docs/design/README.md",
            document("Design", header(up="[04](../04-system-overview.md)")),
        )
        self.write(
            "docs/design/fixture.md",
            document(
                "Fixture",
                header(
                    up="[design/README.md](README.md) · "
                    "[04](../04-system-overview.md)"
                ),
            ),
        )
        self.init_git()
        self.assert_passes(self.run_gate("--check", "reachable"))

    def test_index_root_is_a_reachability_root(self) -> None:
        self.write("docs/README.md", document("Docs"))
        self.write("docs/04-system-overview.md", document("Overview"))
        self.init_git()
        self.assert_passes(self.run_gate("--check", "reachable"))

    def test_broken_up_chain_fails(self) -> None:
        self.write("docs/03-architecture.md", document("Architecture"))
        self.write(
            "docs/design/fixture.md",
            document("Fixture", header(up="[03](../03-architecture.md)")),
        )
        self.init_git()
        self.assert_fails(
            self.run_gate("--check", "reachable"),
            "FAIL docs/design/fixture.md",
            "docs/design/README.md",
            "docs/04-system-overview.md",
        )

    # -- records and empty scope --------------------------------------------

    def test_research_notes_are_exempt(self) -> None:
        self.write("README.md", document("Fixture"))
        self.write("docs/research/note.md", sized("Note", 400))
        self.init_git()
        self.assert_passes(self.run_gate("--check", "headers"))
        self.assert_passes(self.run_gate("--check", "lengths"))

    def test_no_maintained_document_is_an_error(self) -> None:
        self.write("docs/research/only.md", document("Only"))
        self.init_git()
        self.assert_fails(self.run_gate("--check", "headers"), "no maintained")

    # -- baseline ------------------------------------------------------------

    def baseline_entries(self) -> list[str]:
        path = self.path(BASELINE)
        self.assertTrue(os.path.isfile(path), f"{BASELINE} was not written")
        with open(path, encoding="utf-8") as handle:
            lines = [line.strip() for line in handle]
        self.assertTrue(lines and lines[0].startswith("#"), "baseline needs a comment")
        return [line for line in lines if line and not line.startswith("#")]

    def test_emit_baseline_then_default_run_passes(self) -> None:
        self.write_full_tree(broken_design=True)
        self.init_git()
        self.assert_passes(
            self.run_gate("--emit-baseline", self.path(BASELINE)),
        )
        self.assertEqual(self.baseline_entries(), ["docs/design/broken.md"])
        self.assert_passes(self.run_gate())

    def test_baseline_entry_that_now_passes_fails(self) -> None:
        self.write_full_tree(broken_design=True)
        self.init_git()
        self.assert_passes(self.run_gate("--emit-baseline", self.path(BASELINE)))
        self.write(
            "docs/design/broken.md",
            document(
                "Broken",
                header(
                    up="[design/README.md](README.md) · "
                    "[04](../04-system-overview.md)"
                ),
            ),
        )
        self.assert_fails(
            self.run_gate(),
            "stale baseline entry: docs/design/broken.md",
        )

    def test_missing_baseline_is_empty(self) -> None:
        self.write_full_tree()
        self.init_git()
        self.assertFalse(os.path.isfile(self.path(BASELINE)))
        self.assert_passes(self.run_gate())

    def test_baseline_entry_for_a_missing_file_fails(self) -> None:
        self.write_full_tree()
        self.init_git()
        self.write(BASELINE, "# a stale list\n\ndocs/design/gone.md\n")
        self.assert_fails(
            self.run_gate(),
            "stale baseline entry: docs/design/gone.md",
        )

    # -- citations -----------------------------------------------------------

    def test_citations_read_topic_headings_under_docs_topics(self) -> None:
        self.write("docs/decisions/0001-fixture.md", document("ADR-0001"))
        self.write("docs/topics/open.md", "# Open topics\n\n## T-03 · open\n")
        self.write("docs/notes.md", "# Notes\n\nSee T-03.\n")
        self.init_git()
        self.assert_passes(self.run_gate("--check", "citations"))

        self.write("docs/notes.md", "# Notes\n\nSee T-04.\n")
        self.assert_fails(
            self.run_gate("--check", "citations"),
            "T-04 does not exist",
            "highest is 3",
        )


if __name__ == "__main__":
    unittest.main()
